
import "server-only";
import path from "node:path";
import PDFDocument from "pdfkit";
import type { toPayrollDetail } from "@/mappers/payroll.mapper";

type Slip = ReturnType<typeof toPayrollDetail>;

const months = [
  "January", "February", "March", "April",
  "May", "June", "July", "August",
  "September", "October", "November", "December",
];

const rupiah = (value: string) =>
  `Rp ${BigInt(value).toLocaleString("id-ID")}`;

/**
 * Presentation only.
 * All values are immutable published snapshots.
 */
export function renderPayrollPdf(slip: Slip): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      layout: "landscape",
      margin: 40,
      font: path.join(
        process.cwd(),
        "assets/fonts/NotoSans-Regular.ttf"
      ),
      info: {
        Title: "Payslip",
        Author: slip.companyNameSnapshot,
      },
    });

    const chunks: Buffer[] = [];

    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.once("error", reject);
    doc.once("end", () => resolve(Buffer.concat(chunks)));

    try {
      doc.registerFont(
        "Regular",
        path.join(process.cwd(), "assets/fonts/NotoSans-Regular.ttf")
      );
      doc.registerFont(
        "Bold",
        path.join(process.cwd(), "assets/fonts/NotoSans-Bold.ttf")
      );

      const left = 40;
      const width = doc.page.width - 80;
      const bottom = doc.page.height - 85;

      const column = (width - 20) / 2;
      const right = left + column + 20;

      let y = 40;
      let page = 1;

      // ---------------------------------------------
      // Text helper
      // ---------------------------------------------

      function text(
        value: string,
        x: number,
        at: number,
        w: number,
        size = 9,
        bold = false,
        align: "left" | "right" | "center" = "left",
        color = "#253747"
      ) {
        doc
          .font(bold ? "Bold" : "Regular")
          .fontSize(size)
          .fillColor(color);

        const measured = doc.widthOfString(value);

        const position =
          align === "right"
            ? x + w - measured
            : align === "center"
              ? x + (w - measured) / 2
              : x;

        doc.text(value, position, at, {
          lineBreak: false,
        });
      }

      // ---------------------------------------------
      // Footer and pagination
      // ---------------------------------------------

      function footer(final = false) {
        if (final) {
          doc
            .strokeColor("#D5DFE5")
            .moveTo(left, doc.page.height - 67)
            .lineTo(left + width, doc.page.height - 67)
            .stroke();

          text(
            `This payslip was automatically generated by the payroll system of ${slip.companyNameSnapshot}. No signature is required.`,
            left,
            doc.page.height - 55,
            width,
            8,
            false,
            "center",
            "#4B5563"
          );
        }

        text(
          `Page ${page}`,
          left,
          doc.page.height - 39,
          width,
          7,
          false,
          "right"
        );
      }

      function newPage() {
        footer();
        doc.addPage();
        page++;
        y = 40;

        text(
          `PAYSLIP · ${months[slip.month - 1]} ${slip.year} · Continued`,
          left,
          y,
          width,
          10,
          true
        );

        y += 28;
      }

      function room(height: number) {
        if (y + height > bottom) {
          newPage();
        }
      }

      // ---------------------------------------------
      // Manual text wrapping
      // ---------------------------------------------

      function lines(
        value: string,
        w: number,
        size = 9,
        bold = false
      ): string[] {
        doc.font(bold ? "Bold" : "Regular").fontSize(size);

        const output: string[] = [];

        for (const paragraph of value
          .replace(/\r\n?/g, "\n")
          .split("\n")) {
          let line = "";

          for (const char of paragraph) {
            if (line && doc.widthOfString(line + char) > w) {
              const space = line.lastIndexOf(" ");

              if (space > 0) {
                output.push(line.slice(0, space));
                line = line.slice(space + 1);
              } else {
                output.push(line);
                line = "";
              }
            }

            line += char;
          }

          output.push(line);
        }

        return output;
      }

      // ---------------------------------------------
      // Header: Logo | Company | Payslip
      // ---------------------------------------------

      const period = `${months[slip.month - 1]} ${slip.year}`;

      const headerY = y;

      const logoWidth = 140;
      const logoHeight = 70;
      const logoGap = 18;

      const payslipWidth = 190;
      const companyGap = 20;

      const companyX = left + logoWidth + logoGap;
      const payslipX = left + width - payslipWidth;
      const companyWidth = payslipX - companyGap - companyX;

      // Logo fits inside 140x70, preserving aspect ratio.
      doc.image(
        path.join(
          process.cwd(),
          "assets/images/company-logo-1.png"
        ),
        left,
        headerY,
        {
          fit: [logoWidth, logoHeight],
          align: "center",
          valign: "center",
        }
      );

      // Company information has its own vertical cursor.

      const contact = [
        slip.companyEmailSnapshot,
        slip.companyPhoneSnapshot,
      ]
        .filter(Boolean)
        .join(" · ");

      const companyRows: {
        value: string;
        size: number;
        bold: boolean;
      }[] = [];

      function addCompanyRows(
        value: string,
        size: number,
        bold = false
      ) {
        if (!value) return;

        for (const line of lines(value, companyWidth, size, bold)) {
          companyRows.push({
            value: line,
            size,
            bold,
          });
        }
      }

      addCompanyRows(slip.companyNameSnapshot, 15, true);
      addCompanyRows(slip.companyAddressSnapshot, 8);
      addCompanyRows(contact, 8);

      // Calculate total height of company information.
      const companyHeight = companyRows.reduce(
        (total, row) => total + row.size + 5,
        0
      );

      // Align company information vertically with logo.
      const headerContentHeight = Math.max(
        logoHeight,
        companyHeight,
        75
      );

      let companyY =
        headerY + (headerContentHeight - companyHeight) / 2;

      for (const row of companyRows) {
        text(
          row.value,
          companyX,
          companyY,
          companyWidth,
          row.size,
          row.bold
        );

        companyY += row.size + 5;
      }

      // Right-aligned payslip information.
      text(
        "PAYSLIP",
        payslipX,
        headerY,
        payslipWidth,
        24,
        true,
        "right"
      );

      text(
        "PAY PERIOD",
        payslipX,
        headerY + 36,
        payslipWidth,
        8,
        true,
        "right"
      );

      text(
        period,
        payslipX,
        headerY + 51,
        payslipWidth,
        11,
        false,
        "right"
      );

      // Header height follows the tallest column.
      y =
        Math.max(
          headerY + logoHeight,
          companyY,
          headerY + 75
        ) + 15;

      room(20);

      doc
        .strokeColor("#D5DFE5")
        .moveTo(left, y)
        .lineTo(left + width, y)
        .stroke();

      y += 12;

      // ---------------------------------------------
      // Employee details / Bank / Account number
      // ---------------------------------------------

      type DetailLine = {
        value: string;
        size: number;
        bold: boolean;
        color: string;
      };

      const detailGap = 20;
      const detailWidth = width - detailGap * 2;

      const employeeWidth = detailWidth * 0.45;
      const bankWidth = detailWidth * 0.25;
      const accountWidth = detailWidth * 0.30;

      const bankX =
        left + employeeWidth + detailGap;

      const accountX =
        bankX + bankWidth + detailGap;

      const employee: DetailLine[] = [
        {
          value: "EMPLOYEE DETAILS",
          size: 8,
          bold: true,
          color: "#596775",
        },
        ...lines(
          slip.employeeNameSnapshot,
          employeeWidth,
          16,
          true
        ).map((value) => ({
          value,
          size: 16,
          bold: true,
          color: "#253747",
        })),
        ...lines(
          slip.employeePositionSnapshot || "",
          employeeWidth,
          10
        )
          .filter(Boolean)
          .map((value) => ({
            value,
            size: 10,
            bold: false,
            color: "#596775",
          })),
      ];

      function paymentLines(
        label: string,
        value: string | null,
        w: number
      ): DetailLine[] {
        if (!value) return [];

        return [
          {
            value: label,
            size: 8,
            bold: true,
            color: "#596775",
          },
          ...lines(value, w, 10).map((value) => ({
            value,
            size: 10,
            bold: false,
            color: "#253747",
          })),
        ];
      }

      const details = [
        {
          x: left,
          w: employeeWidth,
          rows: employee,
        },
        {
          x: bankX,
          w: bankWidth,
          rows: paymentLines(
            "PAYMENT BANK",
            slip.bankName,
            bankWidth
          ),
        },
        {
          x: accountX,
          w: accountWidth,
          rows: paymentLines(
            "ACCOUNT NUMBER",
            slip.accountNumber,
            accountWidth
          ),
        },
      ];

      const maxDetailRows = Math.max(
        ...details.map((detail) => detail.rows.length)
      );

      for (let i = 0; i < maxDetailRows; i++) {
        const height =
          Math.max(
            ...details.map(
              (detail) => detail.rows[i]?.size ?? 0
            )
          ) + 5;

        room(height);

        for (const detail of details) {
          const line = detail.rows[i];

          if (line) {
            text(
              line.value,
              detail.x,
              y,
              detail.w,
              line.size,
              line.bold,
              "left",
              line.color
            );
          }
        }

        y += height;
      }

      y += 10;

      // ---------------------------------------------
      // Earnings / Deductions headings
      // ---------------------------------------------

      function headings() {
        doc
          .rect(left, y, column, 23)
          .fill("#EDF3F3");

        doc
          .rect(right, y, column, 23)
          .fill("#EDF3F3");

        text(
          "EARNINGS",
          left + 8,
          y + 5,
          column - 16,
          10,
          true
        );

        text(
          "DEDUCTIONS",
          right + 8,
          y + 5,
          column - 16,
          10,
          true
        );

        y += 30;

        for (const x of [left, right]) {
          text(
            "DESCRIPTION",
            x,
            y,
            column,
            7,
            true
          );

          text(
            "AMOUNT (IDR)",
            x,
            y,
            column,
            7,
            true,
            "right"
          );
        }

        y += 18;
      }

      room(65);
      headings();

      // ---------------------------------------------
      // Earnings / Deductions items
      // ---------------------------------------------

      const earnings = slip.items.filter(
        (item) => item.category === "EARNING"
      );

      const deductions = slip.items.filter(
        (item) => item.category === "DEDUCTION"
      );

      doc.font("Regular").fontSize(8);

      const amountWidth =
        doc.widthOfString(
          rupiah("999999999999999999")
        ) + 4;

      const nameWidth = column - amountWidth - 8;

      const maxItems = Math.max(
        earnings.length,
        deductions.length,
        1
      );

      for (let index = 0; index < maxItems; index++) {
        const a = earnings[index];
        const b = deductions[index];

        const aLines = lines(
          a?.name ?? (index === 0 ? "—" : ""),
          nameWidth,
          8
        );

        const bLines = lines(
          b?.name ?? (index === 0 ? "—" : ""),
          nameWidth,
          8
        );

        const maxLines = Math.max(
          aLines.length,
          bLines.length
        );

        for (let line = 0; line < maxLines; line++) {
          if (y + 14 > bottom) {
            newPage();
            headings();
          }

          text(
            aLines[line] ?? "",
            left,
            y,
            nameWidth,
            8
          );

          text(
            bLines[line] ?? "",
            right,
            y,
            nameWidth,
            8
          );

          if (line === 0) {
            if (a) {
              text(
                rupiah(a.amount),
                left + column - amountWidth,
                y,
                amountWidth,
                8,
                false,
                "right"
              );
            }

            if (b) {
              text(
                rupiah(b.amount),
                right + column - amountWidth,
                y,
                amountWidth,
                8,
                false,
                "right"
              );
            }
          }

          y += 14;
        }

        y += 6;
      }

      // ---------------------------------------------
      // Totals
      // ---------------------------------------------

      room(105);

      doc
        .strokeColor("#D5DFE5")
        .moveTo(left, y)
        .lineTo(left + width, y)
        .stroke();

      y += 10;

      text(
        "TOTAL EARNINGS",
        left,
        y,
        column,
        9,
        true
      );

      text(
        "TOTAL DEDUCTIONS",
        right,
        y,
        column,
        9,
        true
      );

      y += 18;

      text(
        rupiah(slip.totalEarnings),
        left,
        y,
        column,
        10,
        true,
        "right"
      );

      text(
        rupiah(slip.totalDeductions),
        right,
        y,
        column,
        10,
        true,
        "right"
      );

      y += 26;

      // ---------------------------------------------
      // Take-home pay
      // ---------------------------------------------

      doc
        .rect(left, y, width, 40)
        .fill("#EDF3F3");

      text(
        "TAKE-HOME PAY",
        left + 12,
        y + 12,
        150,
        10,
        true
      );

      text(
        rupiah(slip.takeHomePay),
        left + 170,
        y + 8,
        width - 182,
        16,
        true,
        "right"
      );

      footer(true);
      doc.end();
    } catch (error) {
      doc.destroy();
      reject(error);
    }
  });
}
